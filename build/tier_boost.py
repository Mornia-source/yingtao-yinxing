"""共享的"码长优先"权重加成表。

规则：无论用户当前打了几个字符、无论候选是单字还是词/句，
候选自身编码位数越少，优先级越高——
1位(单键硬性首选) > 2位(单字双拼) > 3位(词组简码) > 4位(全码)。
每一档之间的加成差远大于该档内任何真实权重的最大值，保证跨档时
位数少的永远排在前面，档内再按原始词频排序。
"""

# 实测最大真实权重：单字表(8105.dict.yaml)约1.5e7，词库(base.dict.yaml)约6.6e5。
# 1位档要压过"2位档最大值(1e8+1.5e7)"和下面 PRIORITY_OVERRIDES 的 9e8，
# 所以取 1e9；总权重上限约 1.015e9，仍在 2^31 以内。
TIER_BOOST = {
    1: 1_000_000_000,
    2: 100_000_000,
    3: 50_000_000,
    4: 0,
}

# 单键硬性首选：只按一个字母时，候选第一位固定是这个字。
# 实现方式是给这些字额外发一条"1位编码"的词条，靠上面 TIER_BOOST[1]
# 的档位压过所有补全候选。除这26个键以外的编码不受影响，用户自己的
# 选字频率(user_dict 调频)照常生效。
SINGLE_KEY_CHARS = {
    "q": "去", "w": "我", "e": "二", "r": "人", "t": "他",
    "y": "一", "u": "是", "i": "出", "o": "哦", "p": "平",
    "a": "啊", "s": "三", "d": "的", "f": "发", "g": "个",
    "h": "和", "j": "就", "k": "可", "l": "了",
    "z": "在", "x": "小", "c": "才", "v": "这", "b": "不",
    "n": "你", "m": "没",
}

# 手动指定"某个编码优先显示哪个候选"的兜底名单，不依赖候选排序机制本身
# 是否可靠——不管排序有没有问题，这里点名的(编码, 文本)组合权重都会被
# 加到远超同编码其它候选的水平。发现类似的撞码问题可以往这里加一条。
PRIORITY_OVERRIDES = {
    ("womf", "我们"): 900_000_000,
}


def boosted_weight(code, weight, text=None):
    w = weight + TIER_BOOST.get(len(code), 0)
    if text is not None:
        w += PRIORITY_OVERRIDES.get((code, text), 0)
    return w
