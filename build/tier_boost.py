"""共享的"码长优先"权重加成表。

*** 重要教训 ***：这份权重是直接写进词典条目、Rime 的 enable_sentence
整句分词动态规划也是拿它来打分选最优切分的——早先给 2/3 位编码加了
1亿/5千万的巨额加成，本意是让"只打2位双拼就能看到同音字排好队"，
结果副作用是：长句连续输入时，两个单字(各带1亿加成，合计2亿)的总权重
远超任何一个词(4位全码，加成0，真实词频顶多几百万)，导致整句分词
几乎永远把词拆成一个个单字，长句连续输入实质上没法用。
"编码位数越少优先"这个展示顺序的诉求，现在完全交给
`lua/char_priority.lua`(在候选流出来之后按结果的字数重排，不影响
词典权重、不影响分词) 来满足，这里不再对分词用的真实权重做任何
人为放大，只保留 1 位档给 26 个单键硬性首选用(那是与分词无关的
单独功能，风险低)。
"""

TIER_BOOST = {
    1: 1_000_000_000,  # 26个单键硬性首选专用，不参与整句分词
    2: 0,
    3: 0,
    4: 0,
}

# 单键硬性首选：只按一个字母时，候选第一位固定是这个字。
# 实现方式是给这些字额外发一条"1位编码"的词条，靠上面 TIER_BOOST[1]
# 的档位压过所有补全候选。除这26个键以外的编码不受影响，用户自己的
# 选字频率(user_dict 调频)照常生效。
SINGLE_KEY_CHARS = {
    "q": "去", "w": "我", "e": "二", "r": "人", "t": "他",
    "y": "一", "u": "是", "i": "出", "o": "哦", "p": "平",
    "a": "啊", "s": "三", "d": "的", "f": "发", "g": "个",
    "h": "和", "j": "就", "k": "可", "l": "了",
    "z": "在", "x": "小", "c": "才", "v": "这", "b": "不",
    "n": "你", "m": "没",
}

# 手动指定"某个编码优先显示哪个候选"的兜底名单，不依赖候选排序机制本身
# 是否可靠——不管排序有没有问题，这里点名的(编码, 文本)组合权重都会被
# 加到远超同编码其它候选的水平。发现类似的撞码问题可以往这里加一条，
# 格式：("编码", "文本"): 加成权重。
PRIORITY_OVERRIDES = {}


def boosted_weight(code, weight, text=None):
    w = weight + TIER_BOOST.get(len(code), 0)
    if text is not None:
        w += PRIORITY_OVERRIDES.get((code, text), 0)
    return w
